#!/usr/bin/env python3
"""Generate the C++ canonical inventory from the shared offline definition."""

import argparse
from pathlib import Path

from dict_builder.pinyin_syllables import SYLLABLE_GROUPS


DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / "engine/src/pinyin_syllables.inc"


def generate(output_path):
    lines = ["// Generated by data/tools/generate_pinyin_syllables.py. Do not edit."]
    for group in SYLLABLE_GROUPS:
        line = "    "
        for syllable in group.split():
            item = f'"{syllable}", '
            if len(line) + len(item) > 100:
                lines.append(line.rstrip())
                line = "    "
            line += item
        lines.append(line.rstrip())
    Path(output_path).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    generate(parser.parse_args().output)


if __name__ == "__main__":
    main()
